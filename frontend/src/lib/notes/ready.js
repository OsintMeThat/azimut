/**
 * The notes a new one can start from without a template of the analyst's own, and
 * how any template's words are filled in when a note is made from it.
 *
 * Each is a working method rather than a form: its parts in the order a reader
 * needs them, guidance lines (`<!--? … -->`) saying what goes where and how to
 * source it, which the editor shows in grey and the PDF never prints, a verdict
 * callout to change once the work is done, and the look it prints in. They hold
 * no case material: no place, no person, no date but the two words filled in.
 *
 * A report printed with a cover writes its own first page (`lib/notes/reportParts.js`):
 * the app's logo on a line of its own, pinned to the top right corner and removed
 * by deleting it, then the title and the day the PDF fills in. It ends on the signature block, as removable.
 *
 * Five more show what a report can hold (`SHOWCASE`): charts, a picture wall, maps with
 * steps, set tables, an infographic, a story. Their figures come set up and empty, never
 * with a number of their own: each opens on its form, its settings or Fill from the case.
 *
 * Templates the analyst keeps live in Settings (`templates.json`, kind `note`) and
 * use the same two words: `{today}` and `{now}`. The words the PDF fills in
 * (`{title}`, `{date}`, `{name}`…) are left as they are.
 */
